def merged_system(system: dict, locale: str) -> dict | None:
    if "PRIMARY_DISPLAY_DOC" not in system:
        return None
    tr = TRANSLATIONS.get(locale, TRANSLATIONS["en"])
    out: dict = {}
    for k, v in system.items():
        if k in NEW_KEYS_ORDER:
            continue
        out[k] = v
        if k == "PRIMARY_DISPLAY_DOC":
            for nk in NEW_KEYS_ORDER:
                out[nk] = tr[nk]
    return out


def main() -> int:
    root = Path(__file__).resolve().parents[1]
    themes = ("classic", "contemporary", "manifest")
    total_changed = 0
    for theme in themes:
        i18n = root / "layer/web" / theme / "app/i18n"
        if not i18n.is_dir():
            print(f"missing {i18n}", file=sys.stderr)
            continue
        for path in sorted(i18n.glob("strings_*.json")):
            stem = path.stem
            locale = stem.replace("strings_", "")
            doc = json.loads(path.read_text(encoding="utf-8"))
            if "SYSTEM" not in doc or not isinstance(doc["SYSTEM"], dict):
                continue
            new_sys = merged_system(doc["SYSTEM"], locale)
            if new_sys is None:
                print(f"  skip {path.relative_to(root)}: no PRIMARY_DISPLAY_DOC", file=sys.stderr)
                continue
            if new_sys == doc["SYSTEM"]:
                continue
            doc["SYSTEM"] = new_sys
            path.write_text(
                json.dumps(doc, ensure_ascii=False, indent=2) + "\n",
                encoding="utf-8",
            )
            total_changed += 1
            print(path.relative_to(root))
    print(f"updated {total_changed} files", file=sys.stderr)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
